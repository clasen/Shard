#!/usr/bin/env python3
"""Extracts the FM operator waveforms of NS2 Obsidian (cOscTypeFM, docs/obsidian/03-oscillators.md)
from the NanoStudio 2 binary into a C header for the ESP32 engine.

  python3 -I fmwaves2h.py "<NanoStudio 2 binary>" <out.h>

The binary keeps a table of 15 pointers (one per waveform) at 0x100c2e110. Their order is the
engine's, not the UI's: it was identified from each table's harmonics and slope (WAVES below).
Each points to a list of {float max_hz, u32 pad, u64 table} entries ending with max_hz = FLT_MAX:
the band-limited versions, chosen by the operator frequency at 44.1 kHz.
Every table is 256 int16 samples plus one guard sample.

The output is derived from NanoStudio 2: keep it local, do not distribute it.
"""
import hashlib
import struct
import sys

SHA256 = "310ed846a896a94943a6353aa3e992bc76bf05d0565032c612621ff80fc65a13"
IMAGE_BASE = 0x100000000  # thin arm64 Mach-O: file offset = address - base
WAVE_TABLE = 0x100c2e110
WAVES = ["Sine", "Parabola", "Triangle", "Saw Up", "Saw Down", "Square", "Half Wave", "Full Wave",
         "Sine 1+2", "Sine 1+3", "Sine 1+4", "Sine 1+5", "Rez 2", "Rez 3", "Rez 5"]
LEN = 257
FLT_MAX = 3.4028234663852886e38


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    data = open(sys.argv[1], "rb").read()
    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit("unexpected binary: the table address is only known for NS2 build " + SHA256[:12])
    u64 = lambda a: struct.unpack_from("<Q", data, a - IMAGE_BASE)[0]
    tables, index = [], {}  # table address -> position in the output
    waves = []
    for w in range(len(WAVES)):
        entries, a = [], u64(WAVE_TABLE + 8 * w)
        while True:
            max_hz = struct.unpack_from("<f", data, a - IMAGE_BASE)[0]
            t = u64(a + 8)
            if t not in index:
                index[t] = len(tables)
                tables.append(struct.unpack_from(f"<{LEN}h", data, t - IMAGE_BASE))
            entries.append((max_hz, index[t]))
            if max_hz >= FLT_MAX:
                break
            a += 16
        waves.append(entries)
    most = max(len(e) for e in waves)

    out = ["// NS2 Obsidian FM operator waveforms, generated by firmware/tools/fmwaves2h.py.",
           "// Derived from NanoStudio 2: keep it local, do not distribute it.",
           "#pragma once", "#include <stdint.h>", "",
           f"constexpr int kFmWaves = {len(WAVES)};  // " + ", ".join(WAVES),
           f"constexpr int kFmBands = {most};",
           f"constexpr int kFmTableLen = {LEN - 1};", "",
           "// Per waveform: the band-limited tables, each used up to max_hz (at 44.1 kHz).",
           "struct FmBand { float maxHz; uint16_t table; };",
           "static const FmBand kFmBandsOf[kFmWaves][kFmBands] = {"]
    for w, entries in zip(WAVES, waves):
        cells = ", ".join(f"{{{'3.4e38f' if hz >= FLT_MAX else f'{hz:g}.0f'}, {t}}}" for hz, t in entries)
        out.append(f"    {{{cells}}},  // {w}")
    out += ["};", "", f"static const int16_t kFmTables[{len(tables)}][{LEN}] = {{"]
    for t in tables:
        out.append("    {" + ",".join(str(v) for v in t) + "},")
    out += ["};", ""]
    open(sys.argv[2], "w").write("\n".join(out))
    print(f"{sys.argv[2]}: {len(WAVES)} waveforms, {len(tables)} tables, {len(tables) * LEN * 2 // 1024} KB")


if __name__ == "__main__":
    main()
