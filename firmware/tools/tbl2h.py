#!/usr/bin/env python3
"""Converts an NS2 wavetable (.tbl, see docs/obsidian/08-wavetable-format.md) into a C header
for the ESP32 engine: one mip per octave (NS2 has 4 per octave), every mip resampled to
1024 samples + 1 guard sample, int16 with a single scale for all frames.

  tbl2h.py <file.tbl> <symbol> <out.h>

The output is derived from NanoStudio 2 content: keep it local, do not distribute it.
"""
import cmath
import math
import struct
import sys

LEN = 1024
OCTAVE_MIPS = 11  # syn::kMips


def read_tbl(path):
    d = open(path, "rb").read()
    size, version, frames, mips, per_octave = struct.unpack_from("<5I", d, 0)
    assert size == len(d) and version == 1, "not a .tbl file"
    pairs = struct.unpack_from("<I", d, 28)[0]
    off = 32 + 8 * pairs
    scales = struct.unpack_from(f"<{frames}f", d, off)
    off += 4 * frames
    table = []  # [mip][frame] -> list of floats (one cycle, no guard)
    for m in range(mips):
        e = struct.unpack_from("<10I", d, off + 40 * m)
        assert e[7] == 0xFEEDFACE
        n, data = e[3], e[8]
        table.append([[v * scales[f] for v in struct.unpack_from(f"<{n}h", d, data + f * (n + 1) * 2)]
                      for f in range(frames)])
    return table, frames, per_octave


def resample(cycle, n):
    """Band-limited resampling of one periodic cycle to n samples (exact for n >= len)."""
    m = len(cycle)
    if m == n:
        return cycle
    half = m // 2
    coef = [sum(cycle[t] * cmath.exp(-2j * math.pi * k * t / m) for t in range(m)) / m for k in range(half)]
    out = []
    for i in range(n):
        x = coef[0].real
        for k in range(1, half):
            x += 2 * (coef[k] * cmath.exp(2j * math.pi * k * i / n)).real
        out.append(x)
    return out


def convert(path):
    """(frames, scale, data): data[frame][octave mip] is LEN + 1 int16 values (with the guard)."""
    table, frames, per_octave = read_tbl(path)
    mips = [[resample(table[o * per_octave][f], LEN) for o in range(OCTAVE_MIPS)] for f in range(frames)]
    peak = max(abs(v) for frame in mips for mip in frame for v in mip)
    scale = peak / 32767.0
    data = []
    for frame in mips:
        rows = []
        for mip in frame:
            q = [max(-32768, min(32767, round(v / scale))) for v in mip]
            rows.append(q + [q[0]])
        data.append(rows)
    return frames, scale, data


def main():
    path, symbol, out_path = sys.argv[1:4]
    frames, scale, data = convert(path)
    with open(out_path, "w") as h:
        h.write(f"// Generated by firmware/tools/tbl2h.py from {path.split('/')[-1]}.\n")
        h.write("// Derived from NanoStudio 2 content: local use only, do not distribute.\n")
        h.write("#pragma once\n#include <stdint.h>\n\n")
        h.write(f"constexpr int k{symbol}Frames = {frames};\n")
        h.write(f"constexpr float k{symbol}Scale = {scale:.9g}f;\n")
        h.write(f"// [frame][octave mip][1024 + guard]\n")
        h.write(f"const int16_t k{symbol}Data[{frames}][{OCTAVE_MIPS}][{LEN + 1}] = {{\n")
        for frame in data:
            h.write(" {\n")
            for q in frame:
                h.write("  {" + ",".join(map(str, q)) + "},\n")
            h.write(" },\n")
        h.write("};\n")


if __name__ == "__main__":
    main()
